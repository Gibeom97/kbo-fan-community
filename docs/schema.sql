DROP TABLE "MEMBER";

CREATE TABLE "MEMBER" (
	"MEMBER_NO"	NUMBER		NOT NULL,
	"TEAM_NO"	NUMBER		NOT NULL,
	"MEMBER_ID"	VARCHAR2(30)		NULL,
	"MEMBER_NAME"	VARCHAR2(20)		NULL,
	"MEMBER_PWD"	VARCHAR2(30)		NULL,
	"EMAIL"	VARCHAR2(100)		NULL,
	"PHONE"	VARCHAR2(11)		NULL,
	"NICKNAME"	VARCHAR2(30)		NULL,
	"GENDER"	CHAR(1)		NULL,
	"SSN"	VARCHAR2(14)		NULL,
	"BIRTH"	CHAR(10)		NULL,
	"CREATE_DATE"	DATE		NULL,
	"PROFILE_IMG"	VARCHAR2(1000)		NULL,
	"LAST_LOGIN_DATE"	DATE		NULL,
	"MEMBER_STATUS"	CHAR(1)		NULL
);

DROP TABLE "TEAM";

